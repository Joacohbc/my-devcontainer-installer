func NormalizeServices(services []any) []SelectedModule {
	result := make([]SelectedModule, 0, len(services))
	for _, s := range services {
		switch v := s.(type) {
		case string:
			result = append(result, SelectedModule{ID: v, Options: map[string]any{}})
		case map[string]any:
			raw, err := json.Marshal(v)
			if err != nil {
				continue
			}
			var sm SelectedModule
			if err := json.Unmarshal(raw, &sm); err != nil {
				continue
			}
			if sm.Options == nil {
				sm.Options = map[string]any{}
			}
			result = append(result, sm)
		case SelectedModule:
			if v.Options == nil {
				v.Options = map[string]any{}
			}
			result = append(result, v)
		}
	}
	return result
}
