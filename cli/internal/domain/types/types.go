func ParseVariant(v string) (string, error) {
	for _, rv := range RemoteVariants {
		if rv == v {
			return v, nil
		}
	}
	return "", fmt.Errorf("invalid --variant: %s. Expected one of: %s", v, strings.Join(RemoteVariants, ", "))
}

